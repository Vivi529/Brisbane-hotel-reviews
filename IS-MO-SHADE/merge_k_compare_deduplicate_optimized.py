# -*- coding: utf-8 -*-
"""
Merge K-sharded five-algorithm benchmark results generated by
run_five_algorithm_comparison_resume_optimized.py.

Core rules
----------
1. Final PF quality metrics are always recomputed from the merged Pareto fronts
   with the optimized runner. Existing per-shard HV/IGD+/epsilon values are not
   trusted as final merged results.
2. HV-FE and IGD+-FE curves are rebuilt from raw snapshot points, using the
   existing hv_fe_curve.csv files only as checkpoint metadata. This guarantees
   one common implementation and preserves empty early checkpoints.
3. When duplicate run keys exist, the selected run, Pareto front, convergence
   history, checkpoint metadata, and snapshot points must all come from the
   same selected shard.
4. Every fixed (K, rho) block must contain all configured algorithms and seeds.

Edit RUNNER_FILE, SHARD_DIRS, and MERGED_OUTPUT_DIR before running.
"""
