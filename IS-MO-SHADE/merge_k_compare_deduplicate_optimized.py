def read_manifest(shard_dir: Path) -> dict[str, Any]:
    path = shard_dir / "_resume" / "manifest.json"
    if not path.exists():
        if REQUIRE_MANIFESTS:
            raise FileNotFoundError(f"Resume manifest not found: {path}")
        return {}
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def validate_manifest_compatibility(
    shard_dirs: tuple[Path, ...],
) -> tuple[pd.DataFrame, dict[str, Any]]:
    manifests: list[dict[str, Any]] = []
    rows: list[dict[str, Any]] = []

    for directory in shard_dirs:
        manifest = read_manifest(directory)
        configuration = manifest.get("configuration", {})
        manifests.append(configuration)
        rows.append(
            {
                "shard": str(directory.resolve()),
                "schema_version": manifest.get("schema_version"),
                "signature": manifest.get("signature"),
                "runner_sha256": configuration.get("runner_sha256"),
                "core_sha256": configuration.get("core_sha256"),
                "moead_adapter_sha256": configuration.get("moead_adapter_sha256"),
                "shamode_adapter_sha256": configuration.get("shamode_adapter_sha256"),
                "seeds": normalized_json(configuration.get("seeds")),
                "generations": configuration.get("generations"),
                "n_options": configuration.get("n_options"),
                "max_active_action_scenarios": normalized_json(
                    configuration.get("max_active_action_scenarios")
                ),
                "coverage_threshold_scenarios": normalized_json(
                    configuration.get("coverage_threshold_scenarios")
                ),
                "algorithms": normalized_json(configuration.get("algorithms")),
                "population_multiplier": configuration.get("population_multiplier"),
                "minimum_population_size": configuration.get("minimum_population_size"),
                "maximum_population_size": configuration.get("maximum_population_size"),
                "fixed_generation_budget": configuration.get("fixed_generation_budget"),
                "metric_block_size": configuration.get("metric_block_size"),
                "moead_config": normalized_json(configuration.get("moead_config")),
                "hv_fe_checkpoint_fractions": normalized_json(
                    configuration.get("hv_fe_checkpoint_fractions")
                ),
            }
        )

    comparison = pd.DataFrame(rows)
    if comparison.empty:
        raise RuntimeError("No shard manifests were loaded.")

    critical_fields = [
        "schema_version",
        "core_sha256",
        "moead_adapter_sha256",
        "shamode_adapter_sha256",
        "seeds",
        "generations",
        "n_options",
        "coverage_threshold_scenarios",
        "algorithms",
        "population_multiplier",
        "minimum_population_size",
        "maximum_population_size",
        "fixed_generation_budget",
        "metric_block_size",
        "moead_config",
        "hv_fe_checkpoint_fractions",
    ]

    missing_fields = [
        field for field in critical_fields if comparison[field].isna().any()
    ]
    # JSON-encoded None appears as the literal string "null".
    missing_fields.extend(
        field
        for field in critical_fields
        if comparison[field].astype(str).eq("null").any() and field not in missing_fields
    )
    if missing_fields:
        raise RuntimeError(
            "Shard manifests are missing optimization-critical fields: "
            f"{missing_fields}\n{comparison[['shard'] + missing_fields].to_string(index=False)}"
        )

    inconsistent = [
        field for field in critical_fields if comparison[field].astype(str).nunique() > 1
    ]
    if inconsistent:
        raise RuntimeError(
            "Shard manifests differ on optimization-critical fields: "
            f"{inconsistent}\n"
            + comparison[["shard"] + inconsistent].to_string(index=False)
        )

    if comparison["runner_sha256"].dropna().astype(str).nunique() > 1:
        print(
            "WARNING: runner_sha256 differs across K shards. This is acceptable only "
            "when the differences are limited to shard-specific settings such as K and "
            "OUTPUT_DIR. Final PF and HV-FE metrics will be recomputed uniformly with "
            f"{RUNNER_FILE.name}."
        )

    return comparison, manifests[0]


def validate_shard_k_configuration(
    shard_dir: Path,
    frame: pd.DataFrame,
    manifest: dict[str, Any],
) -> None:
    configured = {
        int(value) for value in manifest.get("max_active_action_scenarios", [])
    }
    observed = set(frame["max_active_actions"].astype(int).unique())
    if configured and observed != configured:
        raise RuntimeError(
            f"Shard K mismatch for {shard_dir}: manifest={sorted(configured)}, "
            f"run_metrics={sorted(observed)}"
        )


def validate_runner_against_manifest(runner: Any, common: dict[str, Any]) -> None:
    manifest_algorithms = tuple(
        str(item["name"]) for item in common.get("algorithms", [])
    )
    runner_algorithms = tuple(str(value) for value in runner.ALGORITHM_NAMES)
    if manifest_algorithms != runner_algorithms:
        raise RuntimeError(
            "The merge runner algorithm order differs from the shard manifests.\n"
            f"Manifest: {manifest_algorithms}\nRunner:   {runner_algorithms}"
        )

    manifest_checkpoints = tuple(
        round(float(value), 10)
        for value in common.get("hv_fe_checkpoint_fractions", [])
    )
    runner_checkpoints = tuple(
        round(float(value), 10)
        for value in runner.HV_FE_CHECKPOINT_FRACTIONS
    )
    if manifest_checkpoints != runner_checkpoints:
        raise RuntimeError(
            "HV-FE checkpoint fractions differ between the runner and manifests.\n"
            f"Manifest: {manifest_checkpoints}\nRunner:   {runner_checkpoints}"
        )

    manifest_block_size = int(common.get("metric_block_size"))
    runner_block_size = int(getattr(runner, "METRIC_BLOCK_SIZE", -1))
    if manifest_block_size != runner_block_size:
        raise RuntimeError(
            "The optimized metric block size differs between the runner and manifests: "
            f"manifest={manifest_block_size}, runner={runner_block_size}."
        )


def validate_scenario_completeness(
    metrics_with_source: pd.DataFrame,
    expected_algorithms: Sequence[str],
    expected_seeds: Sequence[int],
    expected_rhos: Sequence[float],
) -> pd.DataFrame:
    expected_algorithms = tuple(str(value) for value in expected_algorithms)
    expected_seeds = tuple(int(value) for value in expected_seeds)
    expected_rhos = tuple(canonical_rho(value) for value in expected_rhos)

    observed_algorithms = set(metrics_with_source["algorithm"].astype(str).unique())
    unexpected_algorithms = observed_algorithms - set(expected_algorithms)
    if unexpected_algorithms:
        raise RuntimeError(f"Unexpected algorithms in run_metrics: {sorted(unexpected_algorithms)}")

    rows: list[dict[str, Any]] = []
    k_levels = sorted(metrics_with_source["max_active_actions"].astype(int).unique())
    expected_pairs = {
        (algorithm, seed)
        for algorithm in expected_algorithms
        for seed in expected_seeds
    }

    for k in k_levels:
        for rho in expected_rhos:
            group = metrics_with_source.loc[
                (metrics_with_source["max_active_actions"] == int(k))
                & np.isclose(
                    metrics_with_source["coverage_threshold"].astype(float),
                    float(rho),
                )
            ]
            run_pairs = set(
                zip(group["algorithm"].astype(str), group["seed"].astype(int))
            )
            missing = sorted(expected_pairs - run_pairs)
            extra = sorted(run_pairs - expected_pairs)
            failed = int((group["status"].astype(str) != "success").sum())
            source_count = int(group["__source_shard"].astype(str).nunique()) if len(group) else 0
            rows.append(
                {
                    "max_active_actions": int(k),
                    "coverage_threshold": float(rho),
                    "n_run_records": int(len(group)),
                    "expected_run_records": int(len(expected_pairs)),
                    "n_missing": int(len(missing)),
                    "n_extra": int(len(extra)),
                    "n_failed": failed,
                    "n_source_shards": source_count,
                    "missing_examples": " | ".join(
                        f"{algorithm}/seed={seed}" for algorithm, seed in missing[:10]
                    ),
                    "extra_examples": " | ".join(
                        f"{algorithm}/seed={seed}" for algorithm, seed in extra[:10]
                    ),
                }
            )

    report = pd.DataFrame(rows)
    bad = report.loc[
        (report["n_missing"] > 0)
        | (report["n_extra"] > 0)
        | (report["n_failed"] > 0)
        | (report["n_source_shards"] != 1)
    ]
    if STRICT_COMPLETENESS and not bad.empty:
        raise RuntimeError(
            "Incomplete, failed, or cross-shard scenario blocks were found:\n"
            + bad.to_string(index=False)
        )
    return report


