def load_convergence_history(
    shard_dirs: tuple[Path, ...],
    source_by_run: dict[tuple[int, float, str, int], str],
) -> pd.DataFrame:
    frames: list[pd.DataFrame] = []
    for directory in shard_dirs:
        frame = read_optional_csv(directory, "convergence_history.csv")
        if frame.empty:
            continue
        frame = canonicalize_run_keys(frame)
        frames.append(add_source_metadata(frame, directory))

    convergence = concatenate_nonempty(frames)
    if convergence.empty:
        return convergence
    convergence = filter_to_selected_sources(
        convergence, source_by_run, "convergence_history.csv"
    )

    if "function_evaluations" in convergence.columns:
        convergence["function_evaluations"] = pd.to_numeric(
            convergence["function_evaluations"], errors="raise"
        ).astype(int)
        keys = RUN_KEY_COLUMNS + ["function_evaluations"]
    elif "generation" in convergence.columns:
        convergence["generation"] = pd.to_numeric(
            convergence["generation"], errors="raise"
        ).astype(int)
        keys = RUN_KEY_COLUMNS + ["generation"]
    else:
        raise RuntimeError(
            "convergence_history.csv has neither function_evaluations nor generation."
        )

    convergence = deduplicate_records(
        convergence,
        keys,
        "convergence_history.csv",
        MERGED_OUTPUT_DIR / "duplicate_convergence_history_audit.csv",
    )
    return convergence.drop(
        columns=["__source_shard", "__source_row"], errors="ignore"
    )


def overall_algorithm_summary(metrics: pd.DataFrame) -> pd.DataFrame:
    successful = metrics.loc[metrics["status"] == "success"].copy()
    preferred_metrics = [
        "hypervolume",
        "igd_plus",
        "epsilon_plus",
        "spacing",
        "objective_extent",
        "hv_fe_auc",
        "runtime_seconds",
        "feasible_rate",
        "nontrivial_feasible_rate",
        "first_fe_nontrivial_feasible_95",
        "pareto_size",
        "recommended_reputation",
        "recommended_choice_gain_pp",
        "recommended_effective_cost",
        "recommended_high_priority_coverage",
        "recommended_priority_alignment",
        "recommended_n_active_actions",
    ]
    metric_columns = [
        column for column in preferred_metrics if column in successful.columns
    ]
    rows: list[dict[str, Any]] = []
    for algorithm, group in successful.groupby("algorithm", sort=True):
        row: dict[str, Any] = {
            "algorithm": str(algorithm),
            "n_successful_runs": int(len(group)),
            "n_scenarios": int(
                group[["max_active_actions", "coverage_threshold"]]
                .drop_duplicates()
                .shape[0]
            ),
            "n_seeds": int(group["seed"].nunique()),
        }
        for column in metric_columns:
            values = (
                pd.to_numeric(group[column], errors="coerce")
                .replace([np.inf, -np.inf], np.nan)
                .dropna()
            )
            if values.empty:
                continue
            row[f"{column}_mean"] = float(values.mean())
            row[f"{column}_std"] = (
                float(values.std(ddof=1)) if len(values) > 1 else 0.0
            )
            row[f"{column}_median"] = float(values.median())
            row[f"{column}_q25"] = float(values.quantile(0.25))
            row[f"{column}_q75"] = float(values.quantile(0.75))
        rows.append(row)
    return pd.DataFrame(rows)


