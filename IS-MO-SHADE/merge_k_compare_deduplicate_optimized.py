def load_all_fronts(
    shard_dirs: tuple[Path, ...],
) -> tuple[
    dict[tuple[int, float, str, int], pd.DataFrame],
    dict[tuple[int, float, str, int], str],
]:
    fronts: dict[tuple[int, float, str, int], pd.DataFrame] = {}
    front_sources: dict[tuple[int, float, str, int], str] = {}
    front_paths: dict[tuple[int, float, str, int], str] = {}
    duplicate_front_rows: list[dict[str, Any]] = []

    if COPY_FRONTS_TO_MERGED_DIR:
        MERGED_FRONT_DIR.mkdir(parents=True, exist_ok=True)

    for shard_dir in shard_dirs:
        front_dir = shard_dir / "fronts"
        if not front_dir.exists():
            raise FileNotFoundError(f"Front directory not found: {front_dir}")

        for path in sorted(front_dir.glob("*.csv")):
            frame = pd.read_csv(path)
            if frame.empty:
                raise RuntimeError(f"Empty Pareto-front file: {path}")
            frame = canonicalize_run_keys(frame)

            unique_keys = frame[RUN_KEY_COLUMNS].drop_duplicates()
            if len(unique_keys) != 1:
                raise RuntimeError(f"Front metadata are not constant within {path}")
            k, rho, algorithm, seed = unique_keys.iloc[0].tolist()
            key = run_key_from_values(k, rho, algorithm, seed)
            source = str(shard_dir.resolve())

            if key in fronts:
                duplicate_front_rows.extend(
                    [
                        {
                            **dict(zip(RUN_KEY_COLUMNS, key)),
                            "front_path": front_paths[key],
                            "duplicate_resolution": "discarded_earlier",
                        },
                        {
                            **dict(zip(RUN_KEY_COLUMNS, key)),
                            "front_path": str(path.resolve()),
                            "duplicate_resolution": "kept_last",
                        },
                    ]
                )

            fronts[key] = frame
            front_sources[key] = source
            front_paths[key] = str(path.resolve())

    if not fronts:
        raise RuntimeError("No Pareto fronts were loaded.")

    audit_path = MERGED_OUTPUT_DIR / "duplicate_fronts_audit.csv"
    if duplicate_front_rows:
        duplicate_fronts = pd.DataFrame(duplicate_front_rows).drop_duplicates()
        duplicate_fronts.to_csv(audit_path, index=False, encoding="utf-8-sig")
        print(
            "WARNING: duplicate Pareto-front run keys were found; the last shard "
            "in SHARD_DIRS was retained."
        )
        print(f"Duplicate audit: {audit_path}")
    else:
        _remove_stale_file(audit_path)

    return fronts, front_sources


def validate_front_source_consistency(
    successful_keys: set[tuple[int, float, str, int]],
    source_by_run: dict[tuple[int, float, str, int], str],
    fronts: dict[tuple[int, float, str, int], pd.DataFrame],
    front_sources: dict[tuple[int, float, str, int], str],
) -> None:
    missing_fronts = sorted(successful_keys - set(fronts))
    extra_fronts = sorted(set(fronts) - successful_keys)
    if missing_fronts or extra_fronts:
        raise RuntimeError(
            "Metrics/front mismatch.\n"
            f"Missing fronts: {missing_fronts[:10]}\n"
            f"Extra fronts: {extra_fronts[:10]}"
        )

    mismatches = [
        (key, source_by_run[key], front_sources[key])
        for key in sorted(successful_keys)
        if str(source_by_run[key]) != str(front_sources[key])
    ]
    if mismatches:
        raise RuntimeError(
            "Deduplicated metrics and Pareto fronts were selected from different "
            "shards. First mismatches:\n"
            + "\n".join(
                f"{key}: metrics={metric_source}; front={front_source}"
                for key, metric_source, front_source in mismatches[:10]
            )
        )


def infer_service_element_count(fronts: dict[Any, pd.DataFrame]) -> int:
    expected_columns: tuple[str, ...] | None = None
    for key, frame in fronts.items():
        decision_columns = tuple(
            sorted(
                str(column)
                for column in frame.columns
                if str(column).startswith("x_")
            )
        )
        if not decision_columns:
            raise RuntimeError(
                f"Cannot infer service-element count for front {key}; no x_ columns."
            )
        if expected_columns is None:
            expected_columns = decision_columns
        elif decision_columns != expected_columns:
            raise RuntimeError(
                f"Decision-variable columns differ across fronts. Front {key} is inconsistent."
            )
    assert expected_columns is not None
    return len(expected_columns)


