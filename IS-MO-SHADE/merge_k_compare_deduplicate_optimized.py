def load_module(path: Path, module_name: str) -> Any:
    if not path.exists():
        raise FileNotFoundError(f"Runner file not found: {path}")
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot import runner from {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


def read_required_csv(directory: Path, filename: str) -> pd.DataFrame:
    path = directory / filename
    if not path.exists():
        raise FileNotFoundError(f"Required file not found: {path}")
    return pd.read_csv(path)


def read_optional_csv(directory: Path, filename: str) -> pd.DataFrame:
    path = directory / filename
    return pd.read_csv(path) if path.exists() else pd.DataFrame()


def concatenate_nonempty(frames: Iterable[pd.DataFrame]) -> pd.DataFrame:
    valid = [frame for frame in frames if frame is not None and not frame.empty]
    return pd.concat(valid, ignore_index=True, sort=False) if valid else pd.DataFrame()


def canonical_rho(value: Any) -> float:
    return round(float(value), 10)


def canonicalize_run_keys(frame: pd.DataFrame) -> pd.DataFrame:
    result = frame.copy()
    missing = [column for column in RUN_KEY_COLUMNS if column not in result.columns]
    if missing:
        raise RuntimeError(f"Missing run-key columns: {missing}")

    result["max_active_actions"] = pd.to_numeric(
        result["max_active_actions"], errors="raise"
    ).astype(int)
    result["coverage_threshold"] = (
        pd.to_numeric(result["coverage_threshold"], errors="raise")
        .astype(float)
        .round(10)
    )
    result["algorithm"] = result["algorithm"].astype(str)
    result["seed"] = pd.to_numeric(result["seed"], errors="raise").astype(int)
    return result


def canonicalize_checkpoint_keys(frame: pd.DataFrame) -> pd.DataFrame:
    result = canonicalize_run_keys(frame)
    if "checkpoint_fraction" not in result.columns:
        raise RuntimeError("Missing checkpoint_fraction column.")
    result["checkpoint_fraction"] = (
        pd.to_numeric(result["checkpoint_fraction"], errors="raise")
        .astype(float)
        .round(10)
    )
    return result


def run_key_from_values(k: Any, rho: Any, algorithm: Any, seed: Any) -> tuple[int, float, str, int]:
    return int(k), canonical_rho(rho), str(algorithm), int(seed)


def add_source_metadata(frame: pd.DataFrame, directory: Path) -> pd.DataFrame:
    result = frame.copy()
    result["__source_shard"] = str(directory.resolve())
    result["__source_row"] = np.arange(len(result), dtype=int)
    return result


def _remove_stale_file(path: Path) -> None:
    if path.exists() and path.is_file():
        path.unlink()


def deduplicate_records(
    frame: pd.DataFrame,
    key_columns: Sequence[str],
    dataset_name: str,
    audit_path: Path,
) -> pd.DataFrame:
    """Keep the last input record for each key and write a complete audit."""
    if frame.empty:
        _remove_stale_file(audit_path)
        return frame.copy()

    missing = [column for column in key_columns if column not in frame.columns]
    if missing:
        raise RuntimeError(
            f"Cannot deduplicate {dataset_name}; missing key columns: {missing}"
        )

    duplicate_mask = frame.duplicated(list(key_columns), keep=False)
    if not duplicate_mask.any():
        _remove_stale_file(audit_path)
        return frame.copy().reset_index(drop=True)

    keep_mask = ~frame.duplicated(list(key_columns), keep="last")
    audit = frame.loc[duplicate_mask].copy()
    audit["duplicate_resolution"] = np.where(
        keep_mask.loc[audit.index], "kept_last", "discarded"
    )
    sort_columns = list(key_columns) + [
        column
        for column in ("__source_shard", "__source_row")
        if column in audit.columns
    ]
    audit = audit.sort_values(sort_columns, kind="mergesort")
    audit_path.parent.mkdir(parents=True, exist_ok=True)
    audit.to_csv(audit_path, index=False, encoding="utf-8-sig")

    duplicate_key_count = int(
        frame.loc[duplicate_mask, list(key_columns)].drop_duplicates().shape[0]
    )
    discarded_count = int((duplicate_mask & ~keep_mask).sum())
    print(
        f"WARNING: {dataset_name} contains {duplicate_key_count} duplicate keys; "
        f"discarded {discarded_count} earlier records and kept the last record."
    )
    print(f"Duplicate audit: {audit_path}")
    return frame.loc[keep_mask].copy().reset_index(drop=True)


def selected_source_map(metrics_with_source: pd.DataFrame) -> dict[tuple[int, float, str, int], str]:
    mapping: dict[tuple[int, float, str, int], str] = {}
    columns = RUN_KEY_COLUMNS + ["__source_shard"]
    for k, rho, algorithm, seed, source in metrics_with_source[columns].itertuples(
        index=False, name=None
    ):
        key = run_key_from_values(k, rho, algorithm, seed)
        mapping[key] = str(source)
    return mapping


def filter_to_selected_sources(
    frame: pd.DataFrame,
    source_by_run: dict[tuple[int, float, str, int], str],
    dataset_name: str,
) -> pd.DataFrame:
    if frame.empty:
        return frame.copy()
    if "__source_shard" not in frame.columns:
        raise RuntimeError(f"{dataset_name} has no __source_shard column.")

    keys = [
        run_key_from_values(k, rho, algorithm, seed)
        for k, rho, algorithm, seed in frame[RUN_KEY_COLUMNS].itertuples(
            index=False, name=None
        )
    ]
    expected_sources = pd.Series(
        [source_by_run.get(key) for key in keys], index=frame.index, dtype="object"
    )
    known = expected_sources.notna()
    matching = frame["__source_shard"].astype(str).eq(expected_sources.astype(str))

    ignored_unknown = int((~known).sum())
    ignored_wrong_source = int((known & ~matching).sum())
    if ignored_unknown or ignored_wrong_source:
        print(
            f"INFO: {dataset_name}: ignored {ignored_unknown} rows without a selected "
            f"run and {ignored_wrong_source} rows from non-selected duplicate shards."
        )
    return frame.loc[known & matching].copy().reset_index(drop=True)


def normalized_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


