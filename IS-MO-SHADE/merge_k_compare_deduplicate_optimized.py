def main() -> None:
    print(f"Base directory: {SCRIPT_DIR}")
    print(f"Metric runner: {RUNNER_FILE}")
    print(f"Output directory: {MERGED_OUTPUT_DIR}")

    for directory in SHARD_DIRS:
        if not directory.exists():
            raise FileNotFoundError(f"Shard directory not found: {directory}")

    MERGED_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    MERGED_HV_FE_DIR.mkdir(parents=True, exist_ok=True)
    if COPY_FRONTS_TO_MERGED_DIR:
        MERGED_FRONT_DIR.mkdir(parents=True, exist_ok=True)

    runner = load_module(RUNNER_FILE, "five_algorithm_merge_runner_optimized")

    print("Stage 1/7: validating shard manifests and runner compatibility...")
    manifest_report, common_manifest = validate_manifest_compatibility(SHARD_DIRS)
    validate_runner_against_manifest(runner, common_manifest)

    print("Stage 2/7: loading and consistently deduplicating run metrics...")
    metric_frames: list[pd.DataFrame] = []
    shard_manifests: dict[str, dict[str, Any]] = {}
    for directory in SHARD_DIRS:
        manifest = read_manifest(directory).get("configuration", {})
        shard_manifests[str(directory.resolve())] = manifest
        frame = canonicalize_run_keys(read_required_csv(directory, "run_metrics.csv"))
        validate_shard_k_configuration(directory, frame, manifest)
        metric_frames.append(add_source_metadata(frame, directory))

    metrics_with_source = concatenate_nonempty(metric_frames)
    if metrics_with_source.empty:
        raise RuntimeError("No run_metrics records were loaded.")

    duplicate_mask = metrics_with_source.duplicated(RUN_KEY_COLUMNS, keep=False)
    duplicate_full_path = MERGED_OUTPUT_DIR / "duplicate_run_metrics_full.csv"
    if duplicate_mask.any():
        metrics_with_source.loc[duplicate_mask].sort_values(
            RUN_KEY_COLUMNS + ["__source_shard", "__source_row"], kind="mergesort"
        ).to_csv(duplicate_full_path, index=False, encoding="utf-8-sig")
    else:
        _remove_stale_file(duplicate_full_path)

    metrics_with_source = deduplicate_records(
        metrics_with_source,
        RUN_KEY_COLUMNS,
        "run_metrics.csv",
        MERGED_OUTPUT_DIR / "duplicate_run_metrics_audit.csv",
    )
    source_by_run = selected_source_map(metrics_with_source)

    expected_algorithms = tuple(
        str(item["name"]) for item in common_manifest["algorithms"]
    )
    expected_seeds = tuple(int(value) for value in common_manifest["seeds"])
    expected_rhos = tuple(
        float(value) for value in common_manifest["coverage_threshold_scenarios"]
    )
    completeness = validate_scenario_completeness(
        metrics_with_source,
        expected_algorithms,
        expected_seeds,
        expected_rhos,
    )

    metrics = metrics_with_source.drop(
        columns=["__source_shard", "__source_row"], errors="ignore"
    )

    print("Stage 3/7: loading Pareto fronts and recomputing final PF metrics...")
    fronts, front_sources = load_all_fronts(SHARD_DIRS)
    successful_keys = {
        run_key_from_values(
            row.max_active_actions,
            row.coverage_threshold,
            row.algorithm,
            row.seed,
        )
        for row in metrics.loc[metrics["status"] == "success"].itertuples()
    }
    validate_front_source_consistency(
        successful_keys, source_by_run, fronts, front_sources
    )

    if COPY_FRONTS_TO_MERGED_DIR:
        for key in sorted(successful_keys):
            k, rho, algorithm, seed = key
            filename = (
                f"{runner.scenario_tag(k, rho)}_{algorithm}_seed_{seed}.csv"
            )
            fronts[key].to_csv(
                MERGED_FRONT_DIR / filename, index=False, encoding="utf-8-sig"
            )

    n_options = infer_service_element_count(fronts)
    manifest_n_options = int(common_manifest["n_options"])
    if n_options != manifest_n_options:
        raise RuntimeError(
            f"Service-element count differs: fronts={n_options}, "
            f"manifest={manifest_n_options}."
        )

    population_multiplier = int(common_manifest["population_multiplier"])
    minimum_population = int(common_manifest["minimum_population_size"])
    maximum_population = int(common_manifest["maximum_population_size"])
    runner.METRIC_FRONT_CAP = int(
        np.clip(
            population_multiplier * n_options,
            minimum_population,
            maximum_population,
        )
    )

    # This overwrites any stale quality columns already present in run_metrics.
    metrics, coverage = runner.attach_quality_metrics(metrics, fronts)
    coverage_summary = runner.summarize_pairwise_coverage(coverage)

    print("Stage 4/7: rebuilding HV-FE/IGD+-FE from raw snapshot points...")
    if RECOMPUTE_HV_FE_FROM_SNAPSHOTS:
        checkpoint_metadata = load_checkpoint_metadata(SHARD_DIRS, source_by_run)
        checkpoint_completeness = validate_checkpoint_completeness(
            checkpoint_metadata,
            successful_keys,
            runner.HV_FE_CHECKPOINT_FRACTIONS,
        )
        snapshot_points = load_snapshot_points(SHARD_DIRS, source_by_run)
        validate_final_snapshot_points(
            snapshot_points,
            successful_keys,
            max(runner.HV_FE_CHECKPOINT_FRACTIONS),
        )
        snapshot_records = reconstruct_snapshot_records(
            checkpoint_metadata, snapshot_points
        )
        hv_fe_curve = runner.build_hv_fe_curve(
            metrics, fronts, snapshot_records
        )
    else:
        raise RuntimeError(
            "RECOMPUTE_HV_FE_FROM_SNAPSHOTS=False is disabled for this validated "
            "merge path because reusing per-shard metric values can preserve stale "
            "HV implementations."
        )

    hv_fe_curve, hv_monotonicity = enforce_and_check_hv_fe_monotonicity(
        hv_fe_curve
    )
    metrics = runner.attach_hv_fe_auc(metrics, hv_fe_curve)
    missing_auc = metrics.loc[
        (metrics["status"] == "success") & metrics["hv_fe_auc"].isna(),
        RUN_KEY_COLUMNS,
    ]
    if STRICT_COMPLETENESS and not missing_auc.empty:
        raise RuntimeError(
            "Successful runs without a complete HV-FE AUC were found:\n"
            + missing_auc.head(20).to_string(index=False)
        )
    hv_fe_summary = runner.summarize_hv_fe_curve(hv_fe_curve)
    runner.plot_hv_fe_curves(hv_fe_summary, MERGED_HV_FE_DIR)

    print("Stage 5/7: loading and deduplicating convergence history...")
    convergence = load_convergence_history(SHARD_DIRS, source_by_run)

    print("Stage 6/7: computing summaries and statistical tests...")
    summary = runner.summarize_by_scenario(metrics)
    pairwise = runner.pairwise_tests(metrics)
    friedman, ranks = runner.friedman_and_ranks(metrics)
    stability = runner.recommendation_stability(metrics)
    frequency = runner.recommended_es_frequency(metrics)
    overall = overall_algorithm_summary(metrics)

    configuration = pd.DataFrame(
        [
            {"parameter": "merged_output_dir", "value": str(MERGED_OUTPUT_DIR)},
            {"parameter": "metric_runner", "value": str(RUNNER_FILE)},
            {
                "parameter": "source_shards",
                "value": " | ".join(str(path) for path in SHARD_DIRS),
            },
            {
                "parameter": "n_K_levels",
                "value": int(metrics["max_active_actions"].nunique()),
            },
            {
                "parameter": "n_rho_levels",
                "value": int(metrics["coverage_threshold"].nunique()),
            },
            {
                "parameter": "n_scenarios",
                "value": int(
                    metrics[["max_active_actions", "coverage_threshold"]]
                    .drop_duplicates()
                    .shape[0]
                ),
            },
            {
                "parameter": "algorithms",
                "value": " | ".join(expected_algorithms),
            },
            {"parameter": "seeds", "value": str(expected_seeds)},
            {"parameter": "n_service_elements", "value": int(n_options)},
            {
                "parameter": "metric_front_cap",
                "value": int(runner.METRIC_FRONT_CAP),
            },
            {
                "parameter": "quality_metric_scaling",
                "value": (
                    "joint normalization and empirical reference front within "
                    "each fixed (K, rho) scenario"
                ),
            },
            {
                "parameter": "HV_FE_source",
                "value": (
                    "rebuilt from hv_fe_snapshot_points.csv.gz using checkpoint "
                    "metadata from hv_fe_curve.csv"
                ),
            },
            {
                "parameter": "HV_FE_definition",
                "value": "cumulative attained nondominated front",
            },
            {
                "parameter": "HV_FE_exact_monotonic_clamp",
                "value": bool(ENFORCE_EXACT_HV_FE_MONOTONICITY),
            },
            {"parameter": "pooled_test_blocks", "value": "(K, rho, seed)"},
        ]
    )

    print("Stage 7/7: writing merged files...")
    runner.OUTPUT_DIR = MERGED_OUTPUT_DIR
    runner.OUTPUT_EXCEL = MERGED_EXCEL
    runner.save_outputs(
        metrics,
        summary,
        pairwise,
        friedman,
        ranks,
        coverage,
        coverage_summary,
        convergence,
        hv_fe_curve,
        hv_fe_summary,
        stability,
        frequency,
        configuration,
    )

    extra_csv_outputs = {
        "overall_algorithm_summary.csv": overall,
        "scenario_completeness.csv": completeness,
        "hv_fe_checkpoint_completeness.csv": checkpoint_completeness,
        "hv_fe_monotonicity_check.csv": hv_monotonicity,
        "shard_manifest_comparison.csv": manifest_report,
    }
    for filename, frame in extra_csv_outputs.items():
        frame.to_csv(
            MERGED_OUTPUT_DIR / filename,
            index=False,
            encoding="utf-8-sig",
        )

    if not snapshot_points.empty:
        snapshot_export = snapshot_points.drop(
            columns=["__source_shard", "__source_row"], errors="ignore"
        )
        snapshot_export.to_csv(
            MERGED_OUTPUT_DIR / "hv_fe_snapshot_points.csv.gz",
            index=False,
            encoding="utf-8",
            compression="gzip",
        )

    with pd.ExcelWriter(
        MERGED_EXCEL,
        engine="openpyxl",
        mode="a",
        if_sheet_exists="replace",
    ) as writer:
        overall.to_excel(
            writer, sheet_name="Overall_algorithm_summary", index=False
        )
        completeness.to_excel(
            writer, sheet_name="Scenario_completeness", index=False
        )
        checkpoint_completeness.to_excel(
            writer, sheet_name="HV_FE_checkpoint_check", index=False
        )
        hv_monotonicity.to_excel(
            writer, sheet_name="HV_FE_monotonicity", index=False
        )
        manifest_report.to_excel(
            writer, sheet_name="Shard_manifests", index=False
        )

    expected_outputs = [
        MERGED_EXCEL,
        MERGED_OUTPUT_DIR / "run_metrics.csv",
        MERGED_OUTPUT_DIR / "hv_fe_curve.csv",
        MERGED_OUTPUT_DIR / "overall_algorithm_summary.csv",
        MERGED_OUTPUT_DIR / "scenario_completeness.csv",
        MERGED_OUTPUT_DIR / "hv_fe_checkpoint_completeness.csv",
        MERGED_OUTPUT_DIR / "hv_fe_monotonicity_check.csv",
        MERGED_OUTPUT_DIR / "shard_manifest_comparison.csv",
    ]
    missing_outputs = [path for path in expected_outputs if not path.exists()]
    if missing_outputs:
        raise RuntimeError(
            "The merge finished without creating all required output files:\n"
            + "\n".join(str(path) for path in missing_outputs)
        )

    n_success = int((metrics["status"] == "success").sum())
    n_failed = int((metrics["status"] != "success").sum())
    n_scenarios = int(
        metrics[["max_active_actions", "coverage_threshold"]]
        .drop_duplicates()
        .shape[0]
    )
    n_hv_clamped = int(
        pd.to_numeric(
            hv_monotonicity.get(
                "n_hv_values_clamped", pd.Series(dtype=float)
            ),
            errors="coerce",
        ).fillna(0).sum()
    )

    print("\nMerge completed.")
    print(f"Scenarios: {n_scenarios}")
    print(f"Successful runs: {n_success}; failed runs: {n_failed}")
    print(f"Pareto fronts: {len(fronts)}")
    print(f"HV-FE values clamped for floating-point monotonicity: {n_hv_clamped}")
    print(f"Workbook: {MERGED_EXCEL}")
    print(f"Merged directory: {MERGED_OUTPUT_DIR}")


if __name__ == "__main__":
    main()
