def load_checkpoint_metadata(
    shard_dirs: tuple[Path, ...],
    source_by_run: dict[tuple[int, float, str, int], str],
) -> pd.DataFrame:
    frames: list[pd.DataFrame] = []
    for directory in shard_dirs:
        frame = canonicalize_checkpoint_keys(
            read_required_csv(directory, "hv_fe_curve.csv")
        )
        frames.append(add_source_metadata(frame, directory))

    metadata = concatenate_nonempty(frames)
    metadata = filter_to_selected_sources(
        metadata, source_by_run, "hv_fe_curve checkpoint metadata"
    )
    metadata = deduplicate_records(
        metadata,
        CHECKPOINT_KEY_COLUMNS,
        "hv_fe_curve checkpoint metadata",
        MERGED_OUTPUT_DIR / "duplicate_hv_fe_checkpoint_metadata_audit.csv",
    )
    return metadata


def load_snapshot_points(
    shard_dirs: tuple[Path, ...],
    source_by_run: dict[tuple[int, float, str, int], str],
) -> pd.DataFrame:
    frames: list[pd.DataFrame] = []
    for directory in shard_dirs:
        frame = read_required_csv(directory, "hv_fe_snapshot_points.csv.gz")
        if frame.empty:
            continue
        frame = canonicalize_checkpoint_keys(frame)
        missing = [
            column for column in SNAPSHOT_OBJECTIVE_COLUMNS if column not in frame.columns
        ]
        if missing:
            raise RuntimeError(
                f"Snapshot export in {directory} lacks objective columns: {missing}"
            )
        frames.append(add_source_metadata(frame, directory))

    points = concatenate_nonempty(frames)
    if points.empty:
        return points

    points = filter_to_selected_sources(points, source_by_run, "HV-FE snapshot points")
    for column in SNAPSHOT_OBJECTIVE_COLUMNS:
        points[column] = pd.to_numeric(points[column], errors="raise").astype(float)

    # snapshot_point_index is not used as a deduplication key because duplicated
    # exports can restart point numbering. Objective triples identify the points.
    point_keys = CHECKPOINT_KEY_COLUMNS + SNAPSHOT_OBJECTIVE_COLUMNS
    points = deduplicate_records(
        points,
        point_keys,
        "hv_fe_snapshot_points.csv.gz",
        MERGED_OUTPUT_DIR / "duplicate_hv_fe_snapshot_points_audit.csv",
    )
    return points


def validate_checkpoint_completeness(
    metadata: pd.DataFrame,
    successful_keys: set[tuple[int, float, str, int]],
    checkpoint_fractions: Sequence[float],
) -> pd.DataFrame:
    expected_fractions = tuple(round(float(value), 10) for value in checkpoint_fractions)
    rows: list[dict[str, Any]] = []

    grouped = {
        run_key_from_values(k, rho, algorithm, seed): group
        for (k, rho, algorithm, seed), group in metadata.groupby(
            RUN_KEY_COLUMNS, sort=False
        )
    }

    for key in sorted(successful_keys):
        group = grouped.get(key, pd.DataFrame())
        observed = (
            tuple(sorted(group["checkpoint_fraction"].astype(float).round(10).unique()))
            if not group.empty
            else tuple()
        )
        missing = sorted(set(expected_fractions) - set(observed))
        extra = sorted(set(observed) - set(expected_fractions))
        rows.append(
            {
                **dict(zip(RUN_KEY_COLUMNS, key)),
                "n_checkpoints": int(len(observed)),
                "expected_checkpoints": int(len(expected_fractions)),
                "n_missing": int(len(missing)),
                "n_extra": int(len(extra)),
                "missing_fractions": " | ".join(f"{value:.10g}" for value in missing),
                "extra_fractions": " | ".join(f"{value:.10g}" for value in extra),
            }
        )

    report = pd.DataFrame(rows)
    bad = report.loc[(report["n_missing"] > 0) | (report["n_extra"] > 0)]
    if STRICT_COMPLETENESS and not bad.empty:
        raise RuntimeError(
            "Incomplete HV-FE checkpoint metadata were found:\n"
            + bad.head(20).to_string(index=False)
        )
    return report


def validate_final_snapshot_points(
    points: pd.DataFrame,
    successful_keys: set[tuple[int, float, str, int]],
    final_checkpoint_fraction: float,
) -> None:
    if points.empty:
        raise RuntimeError(
            "No HV-FE snapshot points were loaded, although successful runs exist."
        )
    final_fraction = round(float(final_checkpoint_fraction), 10)
    final_points = points.loc[
        np.isclose(points["checkpoint_fraction"].astype(float), final_fraction)
    ]
    observed = {
        run_key_from_values(k, rho, algorithm, seed)
        for k, rho, algorithm, seed in final_points[RUN_KEY_COLUMNS].itertuples(
            index=False, name=None
        )
    }
    missing = sorted(successful_keys - observed)
    if missing:
        raise RuntimeError(
            "Successful runs without final-checkpoint snapshot points were found. "
            f"First missing keys: {missing[:10]}"
        )


def reconstruct_snapshot_records(
    metadata: pd.DataFrame,
    points: pd.DataFrame,
) -> list[dict[str, Any]]:
    point_groups: dict[tuple[int, float, str, int, float], np.ndarray] = {}
    if not points.empty:
        for keys, group in points.groupby(CHECKPOINT_KEY_COLUMNS, sort=False):
            k, rho, algorithm, seed, fraction = keys
            checkpoint_key = (
                int(k),
                canonical_rho(rho),
                str(algorithm),
                int(seed),
                round(float(fraction), 10),
            )
            values = group[SNAPSHOT_OBJECTIVE_COLUMNS].to_numpy(dtype=float)
            values = values[np.all(np.isfinite(values), axis=1)]
            if len(values):
                values = np.unique(np.round(values, 12), axis=0)
            point_groups[checkpoint_key] = values

    required_metadata = [
        "target_function_evaluations",
        "function_evaluations",
        "function_evaluation_budget",
    ]
    missing = [column for column in required_metadata if column not in metadata.columns]
    if missing:
        raise RuntimeError(f"HV-FE checkpoint metadata lack columns: {missing}")

    records: list[dict[str, Any]] = []
    for row in metadata.itertuples(index=False):
        checkpoint_key = (
            int(row.max_active_actions),
            canonical_rho(row.coverage_threshold),
            str(row.algorithm),
            int(row.seed),
            round(float(row.checkpoint_fraction), 10),
        )
        records.append(
            {
                "max_active_actions": checkpoint_key[0],
                "coverage_threshold": checkpoint_key[1],
                "scenario": getattr(row, "scenario", ""),
                "algorithm": checkpoint_key[2],
                "seed": checkpoint_key[3],
                "checkpoint_fraction": checkpoint_key[4],
                "target_function_evaluations": int(row.target_function_evaluations),
                "function_evaluations": int(row.function_evaluations),
                "function_evaluation_budget": int(row.function_evaluation_budget),
                "points": point_groups.get(
                    checkpoint_key, np.empty((0, 3), dtype=float)
                ).copy(),
            }
        )
    return records


def enforce_and_check_hv_fe_monotonicity(
    curve: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    if curve.empty:
        return curve.copy(), pd.DataFrame()

    result = curve.copy()
    result["hypervolume"] = pd.to_numeric(result["hypervolume"], errors="raise")
    result["igd_plus"] = pd.to_numeric(result["igd_plus"], errors="coerce")

    report_rows: list[dict[str, Any]] = []
    corrected_groups: list[pd.DataFrame] = []

    for keys, group in result.groupby(RUN_KEY_COLUMNS, sort=False):
        ordered = group.sort_values(
            ["actual_fe_fraction", "checkpoint_fraction"], kind="mergesort"
        ).copy()
        raw_hv = ordered["hypervolume"].to_numpy(dtype=float)
        raw_hv_diff = np.diff(raw_hv) if len(raw_hv) > 1 else np.empty(0)
        substantial_hv_drops = int(np.sum(raw_hv_diff < -HV_MONOTONICITY_TOL))
        tiny_hv_drops = int(
            np.sum((raw_hv_diff < 0.0) & (raw_hv_diff >= -HV_MONOTONICITY_TOL))
        )

        if substantial_hv_drops:
            raise RuntimeError(
                "Substantial non-monotone cumulative HV was found after rebuilding "
                f"the curve for run {keys}. Minimum difference={raw_hv_diff.min():.12g}."
            )

        corrected_hv = np.maximum.accumulate(raw_hv)
        n_hv_corrected = int(np.sum(corrected_hv > raw_hv + 0.0))
        if ENFORCE_EXACT_HV_FE_MONOTONICITY:
            ordered["hypervolume"] = corrected_hv

        igd = ordered["igd_plus"].to_numpy(dtype=float)
        finite_positions = np.flatnonzero(np.isfinite(igd))
        if len(finite_positions) > 1:
            finite_igd = igd[finite_positions]
            igd_diff = np.diff(finite_igd)
            substantial_igd_increases = int(np.sum(igd_diff > HV_MONOTONICITY_TOL))
            minimum_igd_diff = float(np.min(igd_diff)) if len(igd_diff) else np.nan
            maximum_igd_diff = float(np.max(igd_diff)) if len(igd_diff) else np.nan
        else:
            substantial_igd_increases = 0
            minimum_igd_diff = np.nan
            maximum_igd_diff = np.nan

        if substantial_igd_increases:
            raise RuntimeError(
                "Cumulative IGD+ increased materially after rebuilding the curve "
                f"for run {keys}; maximum increase={maximum_igd_diff:.12g}."
            )

        k, rho, algorithm, seed = keys
        report_rows.append(
            {
                "max_active_actions": int(k),
                "coverage_threshold": float(rho),
                "algorithm": str(algorithm),
                "seed": int(seed),
                "n_checkpoints": int(len(ordered)),
                "n_substantial_hv_drops": substantial_hv_drops,
                "n_tiny_hv_drops": tiny_hv_drops,
                "n_hv_values_clamped": n_hv_corrected,
                "minimum_raw_hv_difference": (
                    float(np.min(raw_hv_diff)) if len(raw_hv_diff) else np.nan
                ),
                "n_substantial_igd_increases": substantial_igd_increases,
                "minimum_igd_difference": minimum_igd_diff,
                "maximum_igd_difference": maximum_igd_diff,
            }
        )
        corrected_groups.append(ordered)

    corrected = pd.concat(corrected_groups, ignore_index=True, sort=False)
    corrected = corrected.sort_values(
        RUN_KEY_COLUMNS + ["actual_fe_fraction", "checkpoint_fraction"],
        kind="mergesort",
    ).reset_index(drop=True)
    return corrected, pd.DataFrame(report_rows)


